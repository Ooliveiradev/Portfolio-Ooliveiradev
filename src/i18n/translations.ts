const portugueseText = Object.fromEntries(
  Object.entries(englishText).map(([portuguese, english]) => [english, portuguese]),
) as Record<string, string>;

export const translateVisibleText = (value: string, locale: Locale): string => {
  const leading = value.match(/^\s*/)?.[0] ?? '';
  const trailing = value.match(/\s*$/)?.[0] ?? '';
  const source = value.trim();
  if (locale === 'pt') {
    return `${leading}${portugueseText[source] ?? source}${trailing}`;
  }
  return `${leading}${englishText[source] ?? source}${trailing}`;
};
